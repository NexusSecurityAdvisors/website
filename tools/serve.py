import http.server, os, sys
ROOT=sys.argv[1]; CSP=None; PAGE_CSP={}; _rule=None
for line in open(os.path.join(ROOT,'_headers')):
    if line.strip() and not line[0].isspace() and not line.startswith('#'): _rule=line.strip()
    if line.strip().startswith('Content-Security-Policy:'):
        v=line.split(':',1)[1].strip().replace(' upgrade-insecure-requests','')
        if _rule=='/*': CSP=v
        else: PAGE_CSP[_rule]=v   # per-page rules generated by tools/critical/critical_css.mjs
class H(http.server.SimpleHTTPRequestHandler):
    def __init__(s,*a,**k): super().__init__(*a,directory=ROOT,**k)
    def translate_path(s,path):
        p=path.split('?')[0].split('#')[0]
        full=os.path.join(ROOT,p.lstrip('/'))
        if p=='/' : return os.path.join(ROOT,'index.html')
        if not os.path.exists(full) and os.path.exists(full+'.html'): return full+'.html'
        return super().translate_path(path)
    def end_headers(s):
        p=s.path.split('?')[0].split('#')[0]; p=p[:-5] if p.endswith('.html') else p
        c=PAGE_CSP.get(p,CSP)
        if c: s.send_header('Content-Security-Policy',c)
        super().end_headers()
    def log_message(s,*a): pass
http.server.ThreadingHTTPServer(('127.0.0.1',8088),H).serve_forever()
